const translations = { en, ru };

const LanguageContext = createContext({ lang: 'ru', setLang: () => {}, t: (k) => k });

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState('ru');

  useEffect(() => {
    try {
      const saved = localStorage.getItem('gc-lang');
      if (saved && translations[saved]) setLang(saved);
    } catch (e) {
      /* ignore */
    }
  }, []);

  const changeLang = (l) => {
    setLang(l);
    try {
      localStorage.setItem('gc-lang', l);
    } catch (e) {
      /* ignore */
    }
  };

  const t = (key) => translations[lang]?.[key] ?? translations.en[key] ?? key;

  return <LanguageContext.Provider value={{ lang, setLang: changeLang, t }}>{children}</LanguageContext.Provider>;
}

export const useLang = () => useContext(LanguageContext);
export { translations };
